const LEET_MAP = new Map([
  ["0", "o"],
  ["1", "i"],
  ["3", "e"],
  ["4", "a"],
  ["5", "s"],
  ["7", "t"],
  ["@", "a"],
  ["$", "s"],
  ["8", "b"],
]);

type ModerationResult = {
  allowed: boolean;
  score: number;
  reasons: string[];
};

function normalize(input: string): string {
  let normalized = input.toLowerCase();

  normalized = normalized.replace(/ß/g, "ss");

  return normalized

    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")

    .split("")
    .map((c) => LEET_MAP.get(c) ?? c)
    .join("")

    .replace(/[\s\-_\.]/g, "");
}

// Pre-compile regular expressions for bad words to handle arbitrary repetitions
// "fuck" -> /f+u+c+k+/i
const BAD_WORD_REGEXES = BAD_WORDS.map((word) => {
  const pattern = word
    .split("")
    .map((char) => `${char}+`)
    .join("");
  return { word, regex: new RegExp(pattern) };
});

function moderateUsername(username: string): ModerationResult {
  const reasons: string[] = [];
  let score = 0;

  const normalized = normalize(username);

  const hits: string[] = [];
  for (const { word, regex } of BAD_WORD_REGEXES) {
    if (regex.test(normalized)) {
      hits.push(word);
    }
  }

  if (hits.length > 0) {
    score += 1;
    reasons.push(`contains forbidden term: ${hits.join(", ")}`);
  }

  return {
    allowed: score === 0,
    score,
    reasons,
  };
}

// Expose the boolean function for zod schema validation
export const containsBadWord = (username: string): boolean => {
  return !moderateUsername(username).allowed;
};
